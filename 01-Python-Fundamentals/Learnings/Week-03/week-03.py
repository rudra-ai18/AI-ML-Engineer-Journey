# For loop

# 1.   6 at a time

for i in range(7):
    print(i)

# 2.  range(start, stop)

for i in range(2,7):
    print(i)

# 3.   range(start, stop, step)

for i in range(2,11,2):
    print(i)


# 4. Reverse counting range(10, 0, -1)

for i in range(10, 0 ,-1):
    print(i)

